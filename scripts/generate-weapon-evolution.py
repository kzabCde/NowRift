def sprite(family, tier):
    im = Image.new('RGBA', (32, 32))
    d = ImageDraw.Draw(im)
    ink, shade, material, mid, edge, glow, white = PALETTES[family]
    def poly(points, color, outline=ink):
        d.polygon(points, fill=color)
        if outline: d.line(points + [points[0]], fill=outline, width=1)
    def line(points, color, width=1): d.line(points, fill=color, width=width)
    def band(y):
        d.rectangle((14, y, 18, y+1), fill=ink)
        line([(14,y),(17,y)], edge)
    def gem(x, y, radius, color=glow):
        poly([(x,y-radius),(x+radius-1,y),(x,y+radius),(x-radius+1,y)], color)
        line([(x,y-radius+1),(x,y+radius-1)], white)
        if radius > 2: line([(x+1,y-1),(x+radius-2,y)], mid)
    def rune(x,y):
        line([(x,y-1),(x-1,y),(x+1,y+2),(x,y+3)],glow)
    # Stable wrapped grip; shafts and pommels vary with family and milestone.
    if family == 'staff':
        poly([(15,29),(14,14),(13,8),(16,5),(18,8),(17,18),(18,30)], material)
        line([(16,10),(15,18),(16,28)], mid)
        if tier == 0:
            poly([(13,10),(12,5),(14,3),(18,3),(20,6),(18,9),(16,8),(17,6),(15,5),(14,7)],material)
            line([(13,5),(14,4),(17,4)],mid)
        if tier >= 1:
            band(19); band(27)
            line([(14,13),(18,15),(14,17)],shade)
            poly([(12,11),(10,8),(11,5),(13,5),(13,8),(16,10),(19,8),(19,5),(21,5),(22,9),(19,12)],mid)
        if tier >= 2: gem(16,6,4)
        if tier >= 3:
            poly([(13,15),(9,11),(8,7),(9,3),(11,5),(11,9),(14,11)],material)
            poly([(18,14),(23,10),(24,6),(22,3),(21,5),(22,8),(18,11)],material)
            line([(9,6),(10,10),(13,13)],mid); rune(16,15)
        if tier >= 4:
            gem(7,6,3); gem(25,5,3)
            line([(12,19),(14,20),(13,22)],edge)
            line([(20,19),(18,20),(19,22)],edge)
        if tier == 5:
            poly([(11,10),(6,8),(4,4),(5,2),(7,5),(10,6),(11,2),(13,1),(13,6)],mid)
            poly([(20,10),(25,8),(28,4),(27,2),(25,5),(22,6),(21,2),(19,1),(19,6)],mid)
            # Negative space isolates the suspended World Tree seed.
            d.rectangle((14,2,18,10),fill=(0,0,0,0)); gem(16,5,4)
            poly([(15,27),(12,30),(15,29),(16,30),(17,28),(20,30),(18,26)],material)
            line([(12,12),(16,14),(20,12)],edge)
    elif family == 'sword':
        tip = [7,5,3,2,1,1][tier]
        width = [2,3,3,4,5,6][tier]
        poly([(16,tip),(16+width,tip+4),(18,18),(16,21),(13,18),(16-width,tip+4)],material)
        poly([(16,tip+1),(16,18),(14,17),(15-width+2,tip+5)],mid,None)
        line([(16,tip+2),(16,18)],edge if tier>=2 else '#d7dccc')
        d.rectangle((15,22,17,28),fill=ink)
        line([(16,23),(16,28)], '#78534a')
        guard = [4,5,5,6,7,8][tier]
        poly([(16-guard,19),(14,20),(18,20),(16+guard,19),(16+guard,22),(17,23),(15,23),(16-guard,22)],edge)
        line([(13,21),(19,21)],shade)
        gem(16,28,2,edge)
        if tier>=1:
            line([(14,24),(17,25),(15,26)],mid)
            line([(16-width,tip+4),(14,17)],mid)
        if tier>=2:
            rune(17,9); gem(16,21,2)
        if tier>=3:
            poly([(13,7),(10,10),(12,17),(14,18),(13,13)],edge)
            poly([(19,7),(22,10),(20,17),(18,18),(19,13)],edge)
            line([(16,5),(16,17)],glow)
        if tier>=4:
            poly([(12,4),(9,7),(10,12),(12,10),(13,6)],edge)
            poly([(20,4),(23,7),(22,12),(20,10),(19,6)],edge)
            line([(10,7),(11,10)],white); line([(22,7),(21,10)],white)
            line([(10,21),(8,18),(10,19)],glow)
            line([(22,21),(24,18),(22,19)],glow)
        if tier==5:
            # Detached sunmetal fins, luminous spine and crescent guard.
            poly([(12,1),(8,4),(8,8),(10,6),(13,3)],edge)
            poly([(20,1),(24,4),(24,8),(22,6),(19,3)],edge)
            d.rectangle((15,6,17,16),fill=shade)
            line([(16,4),(16,18)],white)
            line([(7,20),(8,23),(12,24),(14,22)],edge)
            line([(25,20),(24,23),(20,24),(18,22)],edge)
    elif family == 'scepter':
        poly([(15,12),(17,12),(18,29),(16,30),(14,28)],shade)
        line([(16,14),(16,28)],mid)
        band(23)
        if tier==0:
            poly([(12,10),(13,7),(19,7),(20,10),(18,14),(14,14)],material)
            line([(14,8),(17,8)],edge)
        else:
            poly([(11,10),(12,7),(14,10),(18,10),(20,7),(21,10),(19,15),(13,15)],material)
            gem(16,7 if tier<3 else 6,3 if tier==1 else 5)
            band(18)
        if tier>=2:
            line([(14,16),(17,17),(15,19)],edge); rune(16,16)
        if tier>=3:
            poly([(12,14),(8,11),(7,5),(10,7),(10,10),(13,11)],material)
            poly([(19,14),(24,11),(25,5),(22,7),(22,10),(19,11)],mid)
            gem(8,5,3);gem(24,5,3)
        if tier>=4:
            gem(6,14,3);gem(26,14,3)
            gem(16,28,2)
            line([(12,20),(14,21),(13,22)],glow)
            line([(20,20),(18,21),(19,22)],glow)
        if tier==5:
            poly([(10,3),(10,1),(13,4),(16,1),(19,4),(22,1),(22,3),(20,8),(18,9),(16,7),(14,9),(12,8)],edge)
            d.rectangle((13,4,19,11),fill=(0,0,0,0));gem(16,6,4)
            gem(5,7,3);gem(27,7,3)
            poly([(11,16),(14,13),(18,13),(21,16),(19,18),(16,16),(13,18)],material)
            line([(14,14),(18,14)],white)
    else:
        poly([(15,8),(17,8),(17,29),(16,30),(14,29)],shade)
        line([(16,11),(16,28)],mid)
        band(24)
        if tier<=1:
            poly([(16,3 if tier==0 else 1),(22,5),(24,9),(22,14),(18,17),(20,11),(19,8),(16,8)],material)
            line([(18,5),(22,8),(22,10),(20,13)],edge if tier else '#c5c7b5')
            if tier: band(17);line([(14,21),(18,22)],edge)
        else:
            poly([(16,1),(22,3),(27,7),(28,12),(24,17),(19,19),(22,14),(23,10),(20,7),(16,8)],material)
            poly([(19,3),(24,6),(26,10),(24,14),(22,16),(24,10),(21,6)],edge)
            gem(18,10,3)
            band(18);line([(14,21),(18,22)],edge)
        if tier>=3:
            poly([(16,4),(12,7),(11,11),(13,14),(13,10),(16,9)],material)
            line([(12,8),(12,10)],glow); rune(16,15)
            line([(25,7),(26,10),(25,12)],glow)
        if tier>=4:
            # Forged split: transparent seam around an exposed molten core.
            line([(22,5),(24,9),(23,13)],ink,2)
            line([(23,6),(25,9),(24,12)],glow)
            poly([(14,18),(11,16),(12,20),(15,22),(19,22),(21,19),(19,18),(18,20)],material)
            line([(12,18),(15,20)],edge)
        if tier==5:
            poly([(18,1),(24,2),(28,5),(30,10),(29,16),(26,21),(21,24),(24,19),(27,14),(27,9),(24,5)],shade)
            line([(25,4),(28,7),(29,11),(28,16),(25,20)],edge)
            line([(26,7),(27,11),(26,15),(24,18)],glow)
            poly([(13,5),(9,3),(10,7),(8,10),(10,14),(11,10),(14,8)],material)
            line([(10,5),(11,7)],glow); gem(16,28,2,glow)
    # Common leather wraps retain a visible grip at the rig's original anchor.
    line([(15,23),(17,23)],mid)
    line([(15,25),(17,25)],shade)
    d.point((16,24), fill=material)
    return im

def png(im):
    stream=io.BytesIO();im.save(stream,format='PNG');return stream.getvalue()

def svg(im, label):
    # Individual integer-grid rects are editable in vector or pixel editors.
    pixels=[]
    for y in range(32):
        for x in range(32):
            r,g,b,a=im.getpixel((x,y))
            if a: pixels.append(f'<rect x="{x}" y="{y}" width="1" height="1" fill="#{r:02x}{g:02x}{b:02x}"/>')
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="32" height="32" shape-rendering="crispEdges"><title>'+label+'</title>'+''.join(pixels)+'</svg>\n').encode()

def generate():
    atlas=Image.new('RGBA',(192,128)); frames=[]; files={}; palettes={}
    for row,family in enumerate(FAMILIES):
        for tier,name in enumerate(TIERS):
            im=sprite(family,tier)
            colors=sorted({'#%02x%02x%02x'%pixel[:3] for pixel in [im.getpixel((x,y)) for y in range(32) for x in range(32)] if pixel[3]})
            palettes[family]=list(dict.fromkeys(palettes.get(family,PALETTES[family])+colors))
            assert im.getbbox()[0]>=1 and im.getbbox()[1]>=1
            assert im.getbbox()[2]<=31 and im.getbbox()[3]<=31
            assert im.getpixel((16,24))[3]==255
            atlas.alpha_composite(im,(tier*32,row*32))
            files[SOURCE/f'{family}-{tier}.svg']=svg(im,f'{family} / {name}')
            frames.append({'family':family,'tier':tier,'name':name,'enhancement':tier*3,'frame':row*6+tier,
                           'rect':[tier*32,row*32,32,32],'bounds':list(im.getbbox()),'grip':[16,24],
                           'sha256':hashlib.sha256(im.tobytes()).hexdigest()})
    assert len({f['sha256'] for f in frames})==24
    files[OUT/'weapon-evolution.png']=png(atlas)
    files[OUT/'weapon-evolution.json']=(json.dumps({'schema':1,'assetKey':'weapon-evolution','size':[192,128],
         'cell':[32,32],'columns':6,'rows':4,'palette':palettes,'frames':frames},indent=2)+'\n').encode()
    return files

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,data in generate().items():
        if args.check:
            assert path.exists() and path.read_bytes()==data, f'Stale generated art: {path}'
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    print('Verified 24 original RGBA sprites, integer-grid SVG sources, stable grips and 192x128 atlas.' if args.check else 'Generated 24 original sprites, SVG sources and atlas metadata.')
