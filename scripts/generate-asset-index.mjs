import process from "node:process";
import console from "node:console";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { createHash } from "node:crypto";
import { format } from "prettier";

const root = resolve(import.meta.dirname, ".."), publicRoot = resolve(root, "public");
function pngs(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = resolve(directory, entry.name);
    return entry.isDirectory() ? pngs(path) : entry.name.endsWith(".png") ? [path] : [];
  });
}
const entries = pngs(publicRoot).sort().map((path) => {
  const bytes = readFileSync(path);
  if (bytes.length < 33 || bytes.subarray(0, 8).toString("hex") !== "89504e470d0a1a0a") throw new Error(`Invalid PNG: ${path}`);
  return { path: "/" + relative(publicRoot, path).replaceAll("\\", "/"), width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20), bytes: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex") };
});
const output = await format("// Generated by scripts/generate-asset-index.mjs. Do not edit by hand.\nexport const ASSET_SOURCES = " + JSON.stringify(entries, null, 2) + " as const;\n", { parser: "typescript" });
const target = resolve(root, "src/game/presentation/asset-index.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) throw new Error("Asset index is stale. Run npm run assets:index after producing artwork.");
  console.log(`Asset source index matches all ${entries.length} public PNGs.`);
} else {
  writeFileSync(target, output);
  console.log(`Indexed ${entries.length} public PNGs (${entries.reduce((sum, entry) => sum + entry.bytes, 0)} bytes).`);
}
